import { ShieldCheck } from "lucide-react";

/** SIMULATED label: every place simulated data appears (AGENT.md hard rule 9). Always this word, in capitals. */
export function SimulatedBadge({ className = "" }: { className?: string }) {
  return (
    <span title="Simulated data: generated by the demo seed, not real trades" className={`num text-[11px] leading-4 text-muted ${className}`}>
      SIMULATED
    </span>
  );
}

/** Real trade whose 1Click quote signature verified. */
export function SignedBadge() {
  return (
    <span
      title="The 1Click quote for this trade carries a valid signature from the 1Click service"
      className="num rounded border border-green/30 px-1.5 py-0.5 text-[11px] leading-4 text-green"
    >
      1Click-signed ✓
    </span>
  );
}

export function ConfidentialBadge({ level }: { level: string }) {
  return (
    <span className="num inline-flex items-center gap-1 rounded border border-line-strong px-1.5 py-0.5 text-[11px] leading-4 text-fg">
      <ShieldCheck size={12} strokeWidth={1.5} aria-hidden />
      confidentiality: {level}
    </span>
  );
}

const STATUS_TONE: Record<string, string> = {
  SUCCESS: "text-up border-up/30",
  SIMULATED: "text-muted border-line-strong",
  REFUNDED: "text-down border-down/40",
  FAILED: "text-down border-down/40",
  INCOMPLETE_DEPOSIT: "text-down border-down/40",
};

export function StatusBadge({ status }: { status: string }) {
  return (
    <span className={`num rounded border px-1.5 py-0.5 text-[11px] leading-4 ${STATUS_TONE[status] ?? "border-line-strong text-fg"}`}>
      {status}
    </span>
  );
}
