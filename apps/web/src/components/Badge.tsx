import { BadgeCheck, FlaskConical, ShieldCheck } from "lucide-react";

/** SIMULATED label: every place simulated data appears (AGENT.md hard rule 9). */
export function SimulatedBadge({ className = "" }: { className?: string }) {
  return (
    <span
      title="Simulated data: generated by the demo seed, not real trades"
      className={`inline-flex items-center gap-1 rounded border border-line-strong px-1.5 py-0.5 text-[11px] font-semibold tracking-wide text-muted ${className}`}
    >
      <FlaskConical size={11} aria-hidden />
      SIMULATED
    </span>
  );
}

/** Real trade whose 1Click quote signature verified. */
export function SignedBadge() {
  return (
    <span
      title="The 1Click quote for this trade carries a valid signature from the 1Click service"
      className="inline-flex items-center gap-1 rounded border border-brass/40 bg-brass-soft px-1.5 py-0.5 text-[11px] font-semibold text-brass"
    >
      <BadgeCheck size={12} aria-hidden />
      1Click-signed ✓
    </span>
  );
}

export function ConfidentialBadge({ level }: { level: string }) {
  return (
    <span className="inline-flex items-center gap-1 rounded border border-line-strong px-1.5 py-0.5 text-[11px] font-semibold text-fg">
      <ShieldCheck size={11} aria-hidden />
      confidentiality: {level}
    </span>
  );
}

const STATUS_TONE: Record<string, string> = {
  SUCCESS: "text-up border-up/40",
  SIMULATED: "text-muted border-line-strong",
  REFUNDED: "text-down border-down/40",
  FAILED: "text-down border-down/40",
  INCOMPLETE_DEPOSIT: "text-down border-down/40",
};

export function StatusBadge({ status }: { status: string }) {
  return (
    <span className={`num rounded border px-1.5 py-0.5 text-[11px] ${STATUS_TONE[status] ?? "border-line-strong text-fg"}`}>
      {status}
    </span>
  );
}
